def discover_virtual_schema(
    *,
    api_key: str | None = None,
    base_url: str | None = None,
    cache_path: str | Path | None = None,
    include_openapi: bool = True,
) -> dict[str, Any]:
    config = load_recipe_db_config()
    client = RecipeDBClient(api_key=api_key, base_url=base_url)
    discovery_config = config["schema_discovery"]
    cache_file = _resolve_cache_path(cache_path or discovery_config["cache_path"])

    result: dict[str, Any] = {
        "version": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "base_url": client.base_url,
        "openapi": _discover_openapi(client, config) if include_openapi else {"checked": [], "found": False},
        "endpoints": {},
        "virtual_tables": {},
        "relationships": [],
        "notes": [
            "Generated by API probing. It is schema evidence, not a guaranteed DB schema.",
            "No API key or Authorization header is stored in this cache.",
        ],
    }

    all_fields: dict[str, dict[str, Any]] = defaultdict(_field_summary)
    for probe in discovery_config["probes"]:
        endpoint_name = probe["endpoint"]
        plan = _probe_plan(endpoint_name, probe, config)
        api_result = client.execute(plan)
        endpoint_summary = _summarize_endpoint(api_result.data, api_result.recipes)
        endpoint_summary.update({
            "ok": api_result.ok,
            "status_code": api_result.status_code,
            "error": api_result.error,
            "path": plan.path,
            "method": plan.method,
            "params_used": plan.params,
        })
        result["endpoints"][endpoint_name] = endpoint_summary

        if _is_token_exhausted(api_result.error):
            result["stopped_early"] = True
            result["stop_reason"] = api_result.error
            break

        for field, summary in endpoint_summary.get("recipe_fields", {}).items():
            _merge_field_summary(all_fields[field], summary)

    result["virtual_tables"] = _build_virtual_tables(dict(all_fields), config)
    result["relationships"] = _infer_relationships(result["virtual_tables"], config)

    if _should_write_cache(result):
        cache_file.parent.mkdir(parents=True, exist_ok=True)
        cache_file.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    else:
        result["cache_write_skipped"] = True
        result["cache_write_skip_reason"] = "No schema evidence was returned before token exhaustion."
    return result


def load_virtual_schema(cache_path: str | Path | None = None) -> dict[str, Any]:
    config = load_recipe_db_config()
    cache_file = _resolve_cache_path(cache_path or config["schema_discovery"]["cache_path"])
    with cache_file.open("r", encoding="utf-8") as f:
        return json.load(f)


def _discover_openapi(client: RecipeDBClient, config: dict[str, Any]) -> dict[str, Any]:
    checked = []
    headers = {"Content-Type": "application/json"}
    if client.api_key:
        headers["Authorization"] = f"Bearer {client.api_key}"

    for path in config["schema_discovery"]["openapi_paths"]:
        url = f"{client.base_url.rstrip('/')}/{path.lstrip('/')}"
        try:
            response = requests.get(url, headers=headers, timeout=client.timeout_seconds)
            checked.append({"path": path, "status_code": response.status_code})
            if not response.ok:
                continue
            data = response.json()
            if isinstance(data, dict) and ("openapi" in data or "swagger" in data):
                return {
                    "checked": checked,
                    "found": True,
                    "path": path,
                    "title": data.get("info", {}).get("title"),
                    "version": data.get("info", {}).get("version"),
                    "path_count": len(data.get("paths", {})),
                }
        except (requests.RequestException, ValueError) as exc:
            checked.append({"path": path, "error": str(exc)})

    return {"checked": checked, "found": False}


def _probe_plan(endpoint_name: str, probe: dict[str, Any], config: dict[str, Any]) -> ApiQueryPlan:
    path_values = probe.get("path_values") or {}
    return ApiQueryPlan(
        label=f"schema_probe:{endpoint_name}",
        method=endpoint_method(endpoint_name, config),
        path=endpoint_path(endpoint_name, config, **path_values),
        params=endpoint_params(endpoint_name, probe.get("params", {}), config),
        priority=0,
        role="schema_probe",
        reason="Virtual schema discovery probe.",
    )


def _summarize_endpoint(data: Any, recipes: list[dict[str, Any]]) -> dict[str, Any]:
    config = load_recipe_db_config()
    recipe_paths = set(config["response"]["recipe_list_paths"])
    summary = {
        "top_level_fields": _summarize_record(data).get("fields", {}) if isinstance(data, dict) else {},
        "recipe_count": len(recipes),
        "recipe_fields": _summarize_records(recipes),
        "nested_collections": {},
    }

    for path, items in _find_record_lists(data):
        if path in recipe_paths:
            continue
        summary["nested_collections"][path] = {
            "count": len(items),
            "fields": _summarize_records(items),
        }
    return summary


def _summarize_records(records: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    fields: dict[str, dict[str, Any]] = defaultdict(_field_summary)
    for record in records:
        for key, value in record.items():
            _observe_value(fields[key], value)
    return dict(fields)


def _summarize_record(record: dict[str, Any]) -> dict[str, Any]:
    return {"fields": _summarize_records([record])}


def _find_record_lists(value: Any, path: str = "") -> list[tuple[str, list[dict[str, Any]]]]:
    found: list[tuple[str, list[dict[str, Any]]]] = []
    if isinstance(value, list):
        records = [item for item in value if isinstance(item, dict)]
        if records:
            found.append((path, records))
        return found
    if isinstance(value, dict):
        for key, child in value.items():
            child_path = f"{path}.{key}" if path else key
            found.extend(_find_record_lists(child, child_path))
    return found


def _field_summary() -> dict[str, Any]:
    return {
        "types": [],
        "nullable": False,
        "numeric_like": False,
        "examples": [],
        "observations": 0,
    }


def _observe_value(summary: dict[str, Any], value: Any) -> None:
    summary["observations"] += 1
    if value is None or value == "":
        summary["nullable"] = True
        value_type = "null"
    else:
        value_type = _infer_type(value)
        if _is_numeric_like(value):
            summary["numeric_like"] = True

    if value_type not in summary["types"]:
        summary["types"].append(value_type)

    examples = summary["examples"]
    if value not in examples and len(examples) < 3 and value not in (None, ""):
        examples.append(value)


def _infer_type(value: Any) -> str:
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int) and not isinstance(value, bool):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, list):
        return "array"
    if isinstance(value, dict):
        return "object"
    if isinstance(value, str):
        return "string"
    return type(value).__name__


def _is_numeric_like(value: Any) -> bool:
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return True
    if not isinstance(value, str):
        return False
    try:
        float(value)
        return True
    except ValueError:
        return False


def _merge_field_summary(target: dict[str, Any], source: dict[str, Any]) -> None:
    target["observations"] += source.get("observations", 0)
    target["nullable"] = target["nullable"] or source.get("nullable", False)
    target["numeric_like"] = target["numeric_like"] or source.get("numeric_like", False)
    for value_type in source.get("types", []):
        if value_type not in target["types"]:
            target["types"].append(value_type)
    for example in source.get("examples", []):
        if example not in target["examples"] and len(target["examples"]) < 3:
            target["examples"].append(example)


def _build_virtual_tables(
    recipe_fields: dict[str, dict[str, Any]],
    config: dict[str, Any],
) -> dict[str, Any]:
    identity_fields = set(config["identity_fields"])
    aliases = config["response_field_aliases"]
    nutrition_logical_fields = set(
        load_sql_schema_config()["relations"]["nutrition"]["columns"]
    )
    tables = {
        "recipes": {
            "source": "api_response_fields",
            "fields": recipe_fields,
            "candidate_primary_keys": [
                field for field in config["identity_fields"]
                if field in recipe_fields and field in identity_fields
            ],
        },
        "recipe_nutrition": {
            "source": "inferred_from_response_field_aliases",
            "fields": {},
        },
        "recipe_dietary": {
            "source": "inferred_from_diet_aliases",
            "fields": {},
        },
    }

    for logical_name, field_names in aliases.items():
        if logical_name not in nutrition_logical_fields:
            continue
        for field_name in field_names:
            if field_name in recipe_fields:
                tables["recipe_nutrition"]["fields"][logical_name] = {
                    "observed_as": field_name,
                    **recipe_fields[field_name],
                }
                break

    for tag in set(config["diet_aliases"].values()):
        if tag in recipe_fields:
            tables["recipe_dietary"]["fields"][tag] = {
                "observed_as": tag,
                **recipe_fields[tag],
            }

    return tables


def _infer_relationships(
    virtual_tables: dict[str, Any],
    config: dict[str, Any],
) -> list[dict[str, str]]:
    key_candidates = virtual_tables["recipes"].get("candidate_primary_keys", [])
    if not key_candidates:
        return []
    recipe_id = key_candidates[0]
    return [
        {"from": "recipe_nutrition.recipe_id", "to": f"recipes.{recipe_id}", "confidence": "virtual"},
        {"from": "recipe_dietary.recipe_id", "to": f"recipes.{recipe_id}", "confidence": "virtual"},
        {"from": "recipe_ingredients.recipe_id", "to": f"recipes.{recipe_id}", "confidence": "virtual"},
    ]


def _is_token_exhausted(error: str | None) -> bool:
    return bool(error and "not enough tokens" in error.lower())


def _should_write_cache(result: dict[str, Any]) -> bool:
    if _schema_evidence_field_count(result) > 0:
        return True
    return not (
        result.get("stopped_early")
        and _is_token_exhausted(result.get("stop_reason"))
    )


def _schema_evidence_field_count(result: dict[str, Any]) -> int:
    tables = result.get("virtual_tables", {})
    if not isinstance(tables, dict):
        return 0
    total = 0
    for table in tables.values():
        if isinstance(table, dict):
            fields = table.get("fields", {})
            if isinstance(fields, dict):
                total += len(fields)
    return total


def _resolve_cache_path(path: str | Path) -> Path:
    path = Path(path)
    if path.is_absolute():
        return path
    return Path(__file__).resolve().parents[3] / path


def _api_key_from_postman(path: str | None, variable_name: str | None = None) -> str | None:
    if not path:
        return None
    variable_name = variable_name or load_recipe_db_config()["postman_api_key_variable"]
    with Path(path).open("r", encoding="utf-8") as f:
        collection = json.load(f)
    for variable in collection.get("variable", []):
        if variable.get("key") == variable_name:
            return variable.get("value")
    return None
